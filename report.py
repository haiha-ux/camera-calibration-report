"""Build results/report.md (+ undistort figure) from the JSON written by calibrate_mono.py / calibrate_stereo.py,
and refresh the results block in README.md."""
import common  # noqa: F401  (first: sets BLAS thread env before cv2 loads)
import json
import re

import cv2
import numpy as np

from common import DATASETS, MODELS, RESULTS, ROOT, image_pairs, load_color

f2 = lambda x: f"{x:.2f}"
f3 = lambda x: f"{x:.3f}"


def mono_table(ds):
    j = json.loads((RESULTS / f"mono_{ds}.json").read_text())
    rows = ["| camera | model | train RMS (OpenCV) | train RMS (same PnP as held-out) | held-out RMS, split 0 | held-out RMS, 20 splits mean ± std (max) | failed splits |", "|---|---|---|---|---|---|---|"]
    for cam, c in j["cameras"].items():
        for m in MODELS:
            r = c["models"][m]
            p, s = r["primary"], r["summary"]
            if p is None:
                rows.append(f"| {cam} | {m} | FAILED | | | | {s['n_failed']}/20 |")
                continue
            rows.append(f"| {cam} | {m} | {f3(p['opencv_rms'])} | {f3(p['train_rms'])} | {f3(p['heldout_rms'])} | "
                        f"{f3(s['heldout_mean'])} ± {f3(s['heldout_std'])} ({f3(s['heldout_max'])}) | {s['n_failed']}/20 |")
    n = j["cameras"]["left"]["models"]["pinhole"]["primary"]
    return j, f"{len(n['train'])} train / {len(n['test'])} held-out views per camera (split 0); {j['cameras']['left']['views_detected']}/{j['cameras']['left']['views_total']} left views detected", "\n".join(rows)


def stereo_table(ds):
    j = json.loads((RESULTS / f"stereo_{ds}.json").read_text())
    p, s = j["primary"], j["summary"]
    e = lambda k, key: f"{f3(p[k][key])}"
    ms = lambda k: f"{s[k]['mean']:.3f} ± {s[k]['std']:.3f}"
    rows = ["| quantity | split 0 | 20 splits mean ± std |", "|---|---|---|",
            f"| baseline [mm] (squares assumed {j['square_mm']} mm) | {f2(p['baseline_mm'])} | {s['baseline_mm']['mean']:.2f} ± {s['baseline_mm']['std']:.2f} |",
            f"| rotation between cameras [deg] | {f2(p['rotation_deg'])} | |",
            f"| stereoCalibrate RMS (train pairs) [px] | {f3(p['stereo_rms'])} | {ms('stereo_rms')} |",
            f"| epipolar abs(dy) mean, train pairs [px] | {e('epipolar_train', 'mean')} | {ms('epi_train_mean')} |",
            f"| epipolar abs(dy) mean, held-out pairs [px] | {e('epipolar_heldout', 'mean')} | {ms('epi_heldout_mean')} |",
            f"| epipolar abs(dy) RMS, held-out pairs [px] | {e('epipolar_heldout', 'rms')} | {ms('epi_heldout_rms')} |",
            f"| epipolar abs(dy) 95th pct / max, held-out [px] | {e('epipolar_heldout', 'p95')} / {e('epipolar_heldout', 'max')} | |"]
    return j, f"{j['pairs_used']}/{j['pairs_total']} pairs detected in both cameras; {len(p['train'])} train / {len(p['test'])} held-out pairs (split 0); model: {j['model']}; failed splits {s['n_failed']}/20", "\n".join(rows)


def undistort_figure(ds, model):
    """Raw vs undistorted held-out view (left camera, split 0). Straight board edges should look straight after."""
    m = json.loads((RESULTS / f"mono_{ds}.json").read_text())["cameras"]["left"]["models"][model]["primary"]
    name = m["test"][0]
    path = {n: a for n, a, _ in image_pairs(ds)}[name]
    im = load_color(path, ds)
    K, D = np.array(m["K"]), np.array(m["D"])
    h, w = im.shape[:2]
    if model == "fisheye":
        Kn = cv2.fisheye.estimateNewCameraMatrixForUndistortRectify(K, D, (w, h), np.eye(3), balance=0.5)
        mp = cv2.fisheye.initUndistortRectifyMap(K, D, np.eye(3), Kn, (w, h), cv2.CV_16SC2)
        und = cv2.remap(im, *mp, cv2.INTER_LINEAR)
    else:
        Kn, _ = cv2.getOptimalNewCameraMatrix(K, D, (w, h), 0)
        und = cv2.undistort(im, K, D, None, Kn)
    for img, t in ((im, "raw"), (und, f"undistorted ({model})")):
        cv2.putText(img, t, (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 255, 255), 2)
    out = np.hstack([im, und])
    out = cv2.resize(out, None, fx=1400 / out.shape[1], fy=1400 / out.shape[1], interpolation=cv2.INTER_AREA)
    cv2.imwrite(str(RESULTS / f"undistort_{ds}.png"), out)


def main():
    parts = ["# Calibration report (generated by report.py; every number comes from results/*.json)\n"]
    for ds, model in (("pinhole", "pinhole"), ("fisheye", "fisheye")):
        undistort_figure(ds, model)
        _, mnote, mt = mono_table(ds)
        _, snote, st = stereo_table(ds)
        parts += [f"## Dataset: {ds} (pattern {DATASETS[ds]['pattern']} inner corners)\n", f"### Single camera\n{mnote}\n", mt, "",
                  f"### Stereo\n{snote}\n", st, "",
                  f"![per-view error](mono_per_view_{ds}.png)", f"![undistorted vs raw](undistort_{ds}.png)", f"![rectified held-out pair](rectified_{ds}.png)\n"]
    md = "\n".join(parts)
    (RESULTS / "report.md").write_text(md)
    readme = ROOT / "README.md"
    block = re.sub(r"\]\((\w+\.png)\)", r"](results/\1)", md.split("\n", 1)[1].replace("## ", "### ").replace("#### ", "##### "))
    txt = readme.read_text()
    readme.write_text(re.sub(r"(<!-- RESULTS -->).*(<!-- /RESULTS -->)", lambda m: f"{m[1]}\n{block}\n{m[2]}", txt, flags=re.S))
    print("report written")


if __name__ == "__main__":
    main()
